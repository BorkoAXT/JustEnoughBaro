    private static readonly IReadOnlyDictionary<string, IReadOnlyDictionary<string, string>> packs =
        new Dictionary<string, IReadOnlyDictionary<string, string>>(StringComparer.OrdinalIgnoreCase)
        {
            [English] = EnglishPack(),
            [Russian] = RussianPack(),
            [Portuguese] = PortuguesePack()
        };

    public static string CurrentLanguage
    {
        get
        {
            string value;
            try { value = GameSettings.CurrentConfig.Language.ToString(); }
            catch { return English; }

            value = value.ToLowerInvariant();
            if (value.Contains("russian") || value.StartsWith("ru")) { return Russian; }
            if (value.Contains("portuguese") || value.StartsWith("pt")) { return Portuguese; }
            return English;
        }
    }

    public static string Get(string key)
    {
        string language = CurrentLanguage;
        if (packs.TryGetValue(language, out IReadOnlyDictionary<string, string>? pack) &&
            pack.TryGetValue(key, out string? translated))
        {
            return translated;
        }
        if (packs[English].TryGetValue(key, out string? fallback)) { return fallback; }
        return TextTools.Humanize(key);
    }

    public static string F(string key, params object[] args) => string.Format(Get(key), args);

